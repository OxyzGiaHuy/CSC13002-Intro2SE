export const translations: Record<string, Translations> = { en, vi };

export const getTranslation = (lang: string, key: string): string => {
  const parts = key.split('.');
  let current: any = translations[lang] || translations.en;
  for (const part of parts) {
    current = current?.[part];
  }
  return current || key;
};

// Hook to get translation object for a language
export const useTranslations = (lang: string): Translations => {
  return translations[lang] || translations.en;
};
